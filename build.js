// Zero-dependency build: `node build.js` writes dist/.
// Set SITE_URL to your domain, e.g. SITE_URL=https://textchef.app/ node build.js
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { gzipSync, deflateSync, crc32 } from 'node:zlib';
import { pathToFileURL, fileURLToPath } from 'node:url';

const SITE = {
  name: 'TextChef',
  url: (process.env.SITE_URL || 'https://dakshrocks21.github.io/TextChef/').replace(/\/?$/, '/'),
};
const CORE_BUDGET = 50 * 1024; // gzipped bytes for the shell (CSS + core JS, ops excluded)

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');
// Styles: src/styles/app.css is Tailwind source. If the standalone CLI is in tools/, recompile
// src/assets/app.css. Otherwise the committed CSS is used as is, so the build needs nothing installed.
const TAILWIND = join(ROOT, 'tools', process.platform === 'win32' ? 'tailwindcss.exe' : 'tailwindcss');
if (existsSync(TAILWIND)) {
  execFileSync(TAILWIND, ['-i', join(ROOT, 'src/styles/app.css'), '-o', join(ROOT, 'src/assets/app.css'), '--minify'], { stdio: ['ignore', 'ignore', 'inherit'] });
}

const { HOME, PAGES, WORD_COUNTER } = await import(pathToFileURL(join(SRC, 'pages.js')).href);

const read = (p) => readFileSync(p, 'utf8');
const write = (p, data) => { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, data); };
const posix = (p) => p.split(sep).join('/');
function* walk(dir) {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

// 1. Op index: metadata for every op so the UI can list them before modules load.
const opsDir = join(SRC, 'assets', 'ops');
const mods = [];
for (const f of readdirSync(opsDir).filter((f) => f.endsWith('.js')).sort()) {
  const m = await import(pathToFileURL(join(opsDir, f)).href);
  mods.push({ file: f, category: m.category, ops: m.default });
}
mods.sort((a, b) => a.category.order - b.category.order);
const categories = mods.map((m) => ({ id: m.category.id, name: m.category.name, color: m.category.color, file: `../ops/${m.file}` }));
const opsMeta = mods.flatMap((m) => m.ops.map((o) => {
  const meta = { id: o.id, name: o.name, cat: m.category.id, keywords: o.keywords || '', options: o.options || [] };
  if (o.magic) meta.magic = true;
  return meta;
}));
const ids = new Set();
for (const o of opsMeta) {
  if (ids.has(o.id)) throw new Error(`Duplicate op id ${o.id}`);
  ids.add(o.id);
}
const indexJs = `// Generated by build.js. Do not edit.\nexport const categories = ${JSON.stringify(categories)};\nexport const ops = ${JSON.stringify(opsMeta)};\n`;

// 2. Collect assets and hash them into one version.
const assets = new Map();
for (const p of walk(join(SRC, 'assets'))) assets.set(posix(relative(join(SRC, 'assets'), p)), readFileSync(p));
assets.set('js/ops-index.js', Buffer.from(indexJs));
const hash = createHash('sha256');
for (const [k, v] of [...assets].sort(([a], [b]) => a.localeCompare(b))) hash.update(k).update(v);
for (const p of walk(SRC)) if (!p.includes(`${sep}assets${sep}`)) hash.update(posix(p)).update(readFileSync(p));
hash.update(JSON.stringify(SITE));
const VERSION = hash.digest('hex').slice(0, 10);

// Check every op used by pages exists, so a typo fails the build instead of a page.
for (const p of PAGES) for (const [id] of p.recipe) if (!ids.has(id)) throw new Error(`Page ${p.slug} uses unknown op ${id}`);

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
for (const [k, v] of assets) write(join(DIST, 'assets', VERSION, k), v);

// 3. Size budget for the shell.
let coreGz = 0, coreRaw = 0, opsGz = 0, fontBytes = 0;
for (const [k, v] of assets) {
  const gz = gzipSync(v, { level: 9 }).length;
  if (k.startsWith('ops/')) opsGz += gz;
  else if (k.startsWith('fonts/')) fontBytes += v.length;
  else { coreGz += gz; coreRaw += v.length; }
}

// 4. HTML pages.
const partials = Object.fromEntries(readdirSync(join(SRC, 'partials')).map((f) => [f.replace(/\.html$/, ''), read(join(SRC, 'partials', f))]));
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function render(template, vars) {
  let html = template.replace(/\{\{> (\w+)\}\}/g, (_, n) => partials[n]);
  html = html.replace(/\{\{> (\w+)\}\}/g, (_, n) => partials[n]);
  return html.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in vars ? vars[k] : m));
}
const APP_JS = ['app', 'registry', 'ops-index', 'recipe', 'stats', 'chips', 'diff', 'mirror', 'wcui', 'shell', 'store', 'engine'];
const WC_JS = ['wc', 'wcui', 'stats', 'shell', 'store'];
function page(template, { path, title, desc, h1 = '', lede = '', preload = [], js = APP_JS, home = false }) {
  const depth = path ? path.split('/').filter(Boolean).length : 0;
  const BASE = depth ? '../'.repeat(depth) : './';
  const vars = {
    TITLE: attr(title), DESC: attr(desc), CANONICAL: SITE.url + path, SITE_URL: SITE.url, SITE_NAME: SITE.name,
    INTRO_CLASS: home ? 'sr' : '',
    INTRO_CLOSE: home ? '' : '<button class="btn sm icon ml-auto self-center" id="intro-close" type="button" aria-label="Hide intro"><svg class="i" aria-hidden="true"><use href="#i-x"/></svg></button>',
    BASE, A: `${BASE}assets/${VERSION}/`, H1: attr(h1), LEDE: attr(lede), PRELOAD: attr(JSON.stringify(preload)),
    PRELOADS: js.map((f) => `<link rel="modulepreload" href="${BASE}assets/${VERSION}/js/${f}.js">`).join('\n'),
  };
  const html = render(template, vars);
  const left = html.match(/\{\{[^}]*\}\}/);
  if (left) throw new Error(`Unfilled ${left[0]} in ${path || 'index'}`);
  write(join(DIST, path, 'index.html'), html);
}
const appTpl = read(join(SRC, 'index.html'));
page(appTpl, { path: '', ...HOME, home: true });
for (const p of PAGES) page(appTpl, { path: `${p.slug}/`, ...p, preload: p.recipe.map(([id, o]) => (o ? [id, o] : [id])) });
page(read(join(SRC, 'word-counter.html')), { path: `${WORD_COUNTER.slug}/`, ...WORD_COUNTER, js: WC_JS });
page(read(join(SRC, 'reset.html')), { path: 'reset/', title: `Reset ${SITE.name}`, desc: '' });

// 5. Icons: the SVG plus PNGs drawn by a tiny rasteriser (no image libraries).
const iconSvg = read(join(SRC, 'icon.svg'));
write(join(DIST, 'icon.svg'), iconSvg);
function png(size) {
  const s = size / 32, SS = 4;
  const lines = [[9, 23, 11], [9, 18, 16], [9, 21, 21]];
  const colorAt = (x, y) => {
    if (Math.hypot(x - 23, y - 16) <= 1.9) return [251, 191, 36];
    for (const [x1, x2, ly] of lines) {
      const cx = Math.max(x1, Math.min(x2, x));
      if (Math.hypot(x - cx, y - ly) <= 1.3) return [255, 255, 255];
    }
    const r = 8, qx = Math.max(r - x, 0, x - (32 - r)), qy = Math.max(r - y, 0, y - (32 - r));
    if (x >= 0 && x <= 32 && y >= 0 && y <= 32 && Math.hypot(qx, qy) <= r) return [79, 79, 209];
    return null;
  };
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let py = 0; py < size; py++) {
    raw[py * (size * 4 + 1)] = 0;
    for (let px = 0; px < size; px++) {
      let R = 0, G = 0, B = 0, A = 0;
      for (let sy = 0; sy < SS; sy++) for (let sx = 0; sx < SS; sx++) {
        const c = colorAt((px + (sx + 0.5) / SS) / s, (py + (sy + 0.5) / SS) / s);
        if (c) { R += c[0]; G += c[1]; B += c[2]; A++; }
      }
      const o = py * (size * 4 + 1) + 1 + px * 4;
      if (A) { raw[o] = Math.round(R / A); raw[o + 1] = Math.round(G / A); raw[o + 2] = Math.round(B / A); }
      raw[o + 3] = Math.round((A / (SS * SS)) * 255);
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const c = Buffer.alloc(4); c.writeUInt32BE(crc32(td) >>> 0);
    return Buffer.concat([len, td, c]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
write(join(DIST, 'icon-192.png'), png(192));
write(join(DIST, 'icon-512.png'), png(512));

write(join(DIST, 'manifest.webmanifest'), JSON.stringify({
  name: SITE.name,
  short_name: SITE.name,
  description: HOME.desc,
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#f4f4f5',
  theme_color: '#4f4fd1',
  icons: [
    { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml' },
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
  ],
}, null, 2));

// 6. Service worker with the full precache list (every page and asset, relative to the SW).
const precache = [];
for (const p of walk(DIST)) {
  const rel = posix(relative(DIST, p));
  if (rel === 'index.html') precache.push('./');
  else if (rel.endsWith('/index.html')) precache.push(rel.slice(0, -'index.html'.length));
  else precache.push(rel);
}
const sw = read(join(SRC, 'sw.js')).replace('__VERSION__', VERSION).replace('__ASSETS__', JSON.stringify(precache, null, 2));
write(join(DIST, 'sw.js'), sw);

// 7. Crawl and hosting files.
const indexable = ['', ...PAGES.map((p) => `${p.slug}/`), `${WORD_COUNTER.slug}/`];
write(join(DIST, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexable.map((p) => `  <url><loc>${SITE.url}${p}</loc></url>`).join('\n')}\n</urlset>\n`);
write(join(DIST, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /reset/\n\nSitemap: ${SITE.url}sitemap.xml\n`);

const noCache = ['/', '/sw.js', '/manifest.webmanifest', '/reset/', ...indexable.filter(Boolean).map((p) => `/${p}`)];
const headers = [
  '/assets/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  ...noCache.flatMap((p) => [p, '  Cache-Control: no-cache']),
  '/*',
  '  X-Content-Type-Options: nosniff',
  '  Referrer-Policy: no-referrer',
].join('\n');
write(join(DIST, '_headers'), headers + '\n');
write(join(DIST, 'netlify.toml'), [
  '# Used when dist/ is deployed directly. The repo root netlify.toml runs the build.',
  '[[headers]]', '  for = "/assets/*"', '  [headers.values]', '    Cache-Control = "public, max-age=31536000, immutable"',
  ...noCache.flatMap((p) => ['[[headers]]', `  for = "${p}"`, '  [headers.values]', '    Cache-Control = "no-cache"']),
].join('\n') + '\n');
write(join(DIST, '.nojekyll'), '');

// 8. Report.
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log(`TextChef ${VERSION}: ${opsMeta.length} ops in ${categories.length} categories, ${indexable.length + 1} pages`);
console.log(`Core shell: ${kb(coreRaw)} raw, ${kb(coreGz)} gzipped (budget ${kb(CORE_BUDGET)}). Op modules: ${kb(opsGz)} gzipped, lazy-loaded. Fonts: ${kb(fontBytes)} woff2.`);
console.log(`Site URL: ${SITE.url}${SITE.url.includes('example.com') ? '  (placeholder, set SITE_URL)' : ''}`);
if (coreGz > CORE_BUDGET) {
  console.error(`Core is over budget by ${kb(coreGz - CORE_BUDGET)}`);
  process.exit(1);
}
